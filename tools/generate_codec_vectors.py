"""Generate reviewable independent constants, not production algorithms."""
from fractions import Fraction
from pathlib import Path
import random
import math
import struct
from xport_compat import xport

r=random.Random(20261104)
def literal(data):return 'b"'+''.join(f'\\x{x:02x}' for x in data)+'"'
lines=['// Generated by tools/generate_codec_vectors.py; xport 3.6.1 + Python Fraction.','','///|','test "independent IEEE to IBM and short storage vectors" {','  let vectors : Array[(Double,Bytes)] = [']
for _ in range(64):
    exponent=r.randint(-260,248)
    value=(1+r.random())*2.0**exponent*r.choice([-1,1])
    raw=xport.v56.ieee_to_ibm(value)
    lines.append(f'    ({value!r}, {literal(raw)}),')
lines+=['  ]','  for (value,raw) in vectors {','    for width=2;width<=8;width=width+1 {','      assert_eq(encode_numeric(Finite(value),width),raw[:width].to_owned())','    }','  }','}','', 'test "independent rational IBM to toward-zero IEEE vectors" {','  let vectors : Array[(Bytes,Double)] = [']
for _ in range(128):
    exponent=r.randrange(128)
    frac=r.randrange(1<<52,1<<56)
    sign=r.randrange(2)
    raw=bytes([exponent+128*sign])+frac.to_bytes(7,'big')
    exact=Fraction(frac,1<<56)*Fraction(16)**(exponent-64)*(-1 if sign else 1)
    value=float(exact)
    if abs(Fraction.from_float(value))>abs(exact):value=math.nextafter(value,0.0)
    lines.append(f'    ({literal(raw)}, {value!r}),')
lines+=['  ]','  for (raw,value) in vectors { assert_eq(decode_numeric(raw),Finite(value)) }','}','']
Path('codec_oracle_wbtest.mbt').write_text('\n'.join(lines))
print('Generated 64 independent encodings × 7 widths and 128 rational toward-zero decoding vectors')
